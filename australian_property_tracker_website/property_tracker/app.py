if d.empty:st.warning('No suburbs match these filters.');st.stop()
d['annual_rent']=d.weekly_rent*(52-vacancy_weeks)
d['annual_expenses']=d.annual_rent*expenses
d['annual_interest']=d.median_price*(1-deposit)*rate
d['annual_cashflow']=d.annual_rent-d.annual_expenses-d.annual_interest
d['net_yield_pct']=(d.annual_rent-d.annual_expenses)/d.median_price*100
d['cash_on_cash_pct']=d.annual_cashflow/(d.median_price*(deposit+closing))*100

