    vacancy_weeks=st.slider('Vacant weeks per year',0,12,2)
    closing=st.slider('Upfront purchase costs % of price (estimate)',0,12,5)/100
    st.caption('Interest-only loan assumption. No tax, depreciation, principal repayments or selling costs.')

