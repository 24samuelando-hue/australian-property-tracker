import os, sqlite3, datetime as dt
import numpy as np
import pandas as pd
import streamlit as st
from pathlib import Path
from app_data import validate

st.set_page_config(page_title='Australian Property Growth Tracker',layout='wide')
DB=os.getenv('TRACKER_DB','property_tracker.sqlite')
COLS=['suburb','state','property_type','median_price','weekly_rent','growth_1y_pct','growth_3y_pct','growth_5y_pct','vacancy_pct','days_on_market','sales_12mo','population_growth_5y_pct','inventory_months','as_of']
NUM=[c for c in COLS if c not in ['suburb','state','property_type','as_of']]

def db():
    con=sqlite3.connect(DB);con.execute('CREATE TABLE IF NOT EXISTS snapshots (recorded_at TEXT, suburb TEXT, state TEXT, property_type TEXT, median_price REAL, weekly_rent REAL, growth_1y_pct REAL, growth_3y_pct REAL, growth_5y_pct REAL, vacancy_pct REAL, days_on_market REAL, sales_12mo REAL, population_growth_5y_pct REAL, inventory_months REAL, as_of TEXT)');return con

def validate(df):
    missing=set(COLS)-set(df.columns)
    if missing: raise ValueError('Missing columns: '+', '.join(sorted(missing)))
    df=df[COLS].copy()
    for c in NUM:df[c]=pd.to_numeric(df[c],errors='coerce')
    df['state']=df['state'].astype(str).str.upper().str.strip()
    df['property_type']=df['property_type'].astype(str).str.lower().str.strip()
    df=df.dropna(subset=['suburb','state','property_type','median_price'])
    df=df[(df.median_price>0)&df.state.isin(['NSW','VIC','QLD','SA','WA','TAS','NT','ACT'])&df.property_type.isin(['house','unit'])]
    return df

def snapshot(df):
    con=db();x=df.copy();x.insert(0,'recorded_at',dt.datetime.now(dt.timezone.utc).isoformat());x.to_sql('snapshots',con,if_exists='append',index=False);con.close()

def latest():
    con=db();df=pd.read_sql_query('SELECT * FROM snapshots',con);con.close()
    if df.empty:return df
    return df.sort_values('recorded_at').drop_duplicates(['suburb','state','property_type'],keep='last')

def scores(df):
    d=df.copy();d['gross_yield_pct']=52*d.weekly_rent/d.median_price*100
    # Normalized percentile ranks avoid overweighting outliers. Missing values receive neutral rank but lower confidence.
    metrics={'growth_3y_pct':.26,'growth_5y_pct':.19,'growth_1y_pct':.12,'population_growth_5y_pct':.15,'vacancy_pct':-.10,'days_on_market':-.07,'inventory_months':-.06,'sales_12mo':.05}
    d['growth_score']=0.
    for c,w in metrics.items():
        r=d[c].rank(pct=True).fillna(.5)
        d['growth_score']+= (r if w>0 else (1-r))*abs(w)*100
    d['growth_score']=d.growth_score.round(1)
    d['missing_signals']=d[list(metrics)].isna().sum(axis=1)
    d['risk_flags']=''
    for idx,row in d.iterrows():
        flags=[]
        if pd.notna(row.vacancy_pct) and row.vacancy_pct>3:flags.append('High vacancy')
        if pd.notna(row.sales_12mo) and row.sales_12mo<30:flags.append('Low sales volume')
        if pd.notna(row.days_on_market) and row.days_on_market>90:flags.append('Slow market')
        if pd.notna(row.inventory_months) and row.inventory_months>6:flags.append('High inventory')
        if pd.notna(row.growth_1y_pct) and row.growth_1y_pct<0:flags.append('Recent price decline')
        if row.missing_signals>2:flags.append('Incomplete data')
        d.at[idx,'risk_flags']=', '.join(flags) if flags else 'No threshold flags'
    return d.sort_values('growth_score',ascending=False)

st.title('🏘️ Australian Property Growth Tracker')
st.caption('Capital-growth-first suburb screener • Australia-wide • data-driven, not investment advice')
